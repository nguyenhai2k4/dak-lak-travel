const themeDefaultCategories: Record<ThemeType, string> = {
  culture: 'Văn hóa & Cồng chiêng',
  coffee: 'Cà phê & Nghỉ dưỡng',
  nature: 'Thiên nhiên & Thác nước',
  cuisine: 'Ẩm thực bản địa',
};

export function findPlaceMeta(
  title: string,
  _location?: string,
  theme: ThemeType = 'coffee'
): Pick<PlaceMeta, 'category' | 'rating' | 'reviews' | 'duration' | 'image'> {
  const lowerTitle = (title || '').toLowerCase();
  const match = dakLakPlaceDirectory.find(
    (p) =>
      lowerTitle.includes(p.title.toLowerCase()) ||
      p.title.toLowerCase().includes(lowerTitle) ||
      (lowerTitle.includes('cà phê') && p.title.includes('Cà phê')) ||
      (lowerTitle.includes('ako dhông') && p.title.includes('Ako Dhông')) ||
      (lowerTitle.includes('ea tân') && p.title.includes('Ea Tân')) ||
      (lowerTitle.includes('đá voi') && p.title.includes('Đá Voi')) ||
      (lowerTitle.includes('hồ lắk') && p.title.includes('Hồ Lắk')) ||
      (lowerTitle.includes('độc mộc') && p.title.includes('Hồ Lắk')) ||
      (lowerTitle.includes('biệt điện') && p.title.includes('Biệt điện')) ||
      (lowerTitle.includes('dray nur') && p.title.includes('Dray Nur')) ||
      (lowerTitle.includes('yok đôn') && p.title.includes('Yok Đôn')) ||
      (lowerTitle.includes('tơng jú') && p.title.includes('Tơng Jú')) ||
      (lowerTitle.includes('bản đôn') && p.title.includes('Bản Đôn')) ||
      (lowerTitle.includes('bún') && p.title.includes('Phan Đình Giót'))
  );

  if (match) return match;

  return {
    category: themeDefaultCategories[theme] || 'Điểm trải nghiệm',
    rating: '4.7',
    reviews: '520',
    duration: '1.5 giờ',
    image: themeCoverImages[theme] || themeCoverImages.coffee,
  };
}
